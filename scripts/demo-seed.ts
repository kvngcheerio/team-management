const PASSWORD = "matchday-demo-pass";
const out: string[] = ["-- Generated by scripts/demo-seed.ts. LOCAL DEMO DATA ONLY.", "PRAGMA foreign_keys = ON;"];
const q = (v: unknown) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table: string, row: Record<string, unknown>) =>
  out.push(`INSERT INTO ${table} (${Object.keys(row).join(", ")}) VALUES (${Object.values(row).map(q).join(", ")});`);
const now = new Date().toISOString();
const hash = (pw: string) => {
  const salt = randomBytes(16);
  const h = pbkdf2Sync(pw.normalize("NFKC"), salt, 100_000, 32, "sha256");
  return `pbkdf2_sha256$100000$${salt.toString("base64")}$${h.toString("base64")}`;
};


const finalizedIds: { id: string; attendees: string[] }[] = [];
function finalizedDay(date: string, pool: { id: string; member: boolean }[]) {
  const dayId = matchDay(date, "finalized", { teams_published_at: now, started_at: now, finalized_at: now });
  const setIds = [0, 1, 2].map(() => randomUUID());
  setIds.forEach((sid, i) => insert("sets", { id: sid, match_day_id: dayId, idx: i + 1, name: SET_NAMES[i], color: SET_COLORS[i] }));
  const roster = pool.map((p, i) => ({ playerId: p.id, setId: setIds[i % 3]!, memberAtLock: p.member }));
  const attendance: Record<string, boolean> = {};
  roster.forEach((r, i) => {
    attendance[r.playerId] = i !== 4; // one no-show
    insert("registrations", { id: randomUUID(), match_day_id: dayId, player_id: r.playerId, status: "confirmed", source: "self", attended: attendance[r.playerId] ? 1 : 0, queued_at: now, created_at: now, updated_at: now });
    insert("roster_entries", { match_day_id: dayId, set_id: r.setId, player_id: r.playerId, role: "starter", is_goalkeeper: 0, member_at_lock: r.memberAtLock ? 1 : 0 });
  });
  const matches: MatchResult[] = [];
  const goals: GoalEvent[] = [];
  const pairs = [[0, 1], [1, 2], [0, 2], [1, 0], [2, 1], [2, 0]];
  pairs.forEach(([h, a], i) => {
    const m: MatchResult = { id: randomUUID(), homeSetId: setIds[h!]!, awaySetId: setIds[a!]!, homeScore: Math.floor(rand() * 3), awayScore: Math.floor(rand() * 3), status: "completed", isPlayoff: false, seq: i + 1 };
    matches.push(m);
    insert("matches", { id: m.id, match_day_id: dayId, seq: i + 1, home_set_id: m.homeSetId, away_set_id: m.awaySetId, home_score: m.homeScore, away_score: m.awayScore, status: "completed", is_playoff: 0, created_at: now, updated_at: now });
    for (const [setId, n] of [[m.homeSetId, m.homeScore], [m.awaySetId, m.awayScore]] as const) {
      const present = roster.filter((r) => r.setId === setId && attendance[r.playerId]);
      for (let g = 0; g < n; g++) {
        const scorer = present[Math.floor(rand() * present.length)]!;
        const others = present.filter((p) => p !== scorer);
        const assist = rand() < 0.6 && others.length ? others[Math.floor(rand() * others.length)]! : null;
        const ev: GoalEvent = { id: randomUUID(), matchId: m.id, setId, kind: "normal", scorerPlayerId: scorer.playerId, assistPlayerId: assist?.playerId ?? null };
        goals.push(ev);
        insert("goal_events", { id: ev.id, match_id: m.id, set_id: setId, kind: "normal", scorer_player_id: ev.scorerPlayerId, assist_player_id: ev.assistPlayerId, created_at: now });
      }
    }
  });
  const state: DayState = { setIds, tiePolicy: "shared", matches, goals, roster, attendance };
  const { winner, stats } = computeDayStats(state);
  finalizedIds.push({ id: dayId, attendees: roster.filter((r) => attendance[r.playerId]).map((r) => r.playerId) });
  if (winner.status === "decided") winner.winnerSetIds.forEach((sid) => out.push(`UPDATE sets SET is_daily_winner = 1 WHERE id = ${q(sid)};`));
  for (const s of stats) {
    insert("day_player_stats", { match_day_id: dayId, player_id: s.playerId, set_id: s.setId, attended: s.attended ? 1 : 0, eligible: s.eligible ? 1 : 0, daily_win: s.dailyWin ? 1 : 0, points: s.points, goals: s.goals, assists: s.assists, own_goals: s.ownGoals });
  }
}

